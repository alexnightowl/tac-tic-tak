/* global __dirname */
// Bakes assets/themes/*.svg into glyphs.ts as XML strings for react-native-svg
// SvgXml (no SVG transformer in Metro). Every fill/stroke becomes
// currentColor, so the icon takes the `color` prop like the web's
// mask-filled glyphs; the one file with a <style> block gets its classes
// inlined (SvgXml ignores CSS). Run after changing the assets:
//   node apps/mobile/src/features/play/themes/build-glyphs.cjs
const fs = require('fs');
const path = require('path');

const dir = path.resolve(__dirname, '../../../../assets/themes');
const out = path.join(__dirname, 'glyphs.ts');

function inlineStyles(xml) {
  const m = /<style>([\s\S]*?)<\/style>/.exec(xml);
  if (!m) return xml;
  const rules = {};
  for (const [, sel, body] of m[1].matchAll(/([^{]+)\{([^}]*)\}/g)) {
    for (const cls of sel.split(',').map((s) => s.trim().replace(/^\./, ''))) {
      rules[cls] = { ...(rules[cls] || {}), ...Object.fromEntries(body.split(';').filter(Boolean).map((d) => d.split(':').map((x) => x.trim()))) };
    }
  }
  return xml
    .replace(m[0], '')
    .replace(/class="([^"]+)"/g, (_, cls) =>
      Object.entries(rules[cls] || {}).map(([k, v]) => `${k}="${v}"`).join(' '),
    );
}

const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    let xml = fs.readFileSync(path.join(dir, f), 'utf8').trim();
    xml = inlineStyles(xml)
      .replace(/ (id|x|y|xml:space)="[^"]*"/g, '')
      .replace(/#7f7f7f/gi, 'currentColor');
    return `  ${JSON.stringify(f.replace(/\.svg$/, ''))}: ${JSON.stringify(xml)},`;
  });

fs.writeFileSync(
  out,
  `// GENERATED by build-glyphs.cjs from assets/themes/*.svg (Lichess theme\n` +
    `// glyphs, see assets/themes/CREDITS.md). Do not edit by hand.\n` +
    `export const THEME_GLYPHS: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`wrote ${entries.length} glyphs to ${out}`);
